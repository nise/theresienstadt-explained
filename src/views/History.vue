              Heinrich Himmler vorgeführt und dieser befehlt den Film zu
              vernichten. Die Existenz der Dreharbeiten werden weiterhin nur
              Fotos des tschechischen Kameramanns bezeugen.
            </p>
            <p>
              Mitglied des Ältestenrates Benjamin Murmelstein bekommt Weils
