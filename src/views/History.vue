          technischer Qualität im Yad Vashem Archiv in Jerusalem.
        </p>

        <h3 class="timelineMajorMarker mt-4">1964</h3>
        <p>
          Ein Fragment des Theresienstädter Films aus den Jahren 1944-1945, in
          der Nachkriegszeit bekannt als
          <i>Der Führer schenkt den Juden eine Stadt</i> wird von der
          Öffentlichkeit "entdeckt", als Přemysl Schönbach beschliesst, das
          einst bei Mšeno gefundene Filmmaterial für seinen Amateur-Film zu
          verwenden. Sein Material wird vom FAMU-Lehrer Vladimír Kressl
          übernommen, der das Fragment identifiziert und über den seltenen Fund
          die Presse benachrichtigt. Von dem Fragment des brennbaren Filmbands
          werden eine Kopie und Negative für die Filmbibliothek des
          Tschechoslowakischen Filminstituts in Prag gemacht.
        </p>

