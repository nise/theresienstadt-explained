              Schweizer Vermittler Benoît Musy. An einer weiteren Projektion
              nimt Rezső Kasztner teil, Vertreter der Organisation Va'ada –
              Hilfs- und Rettungskomitee in Budapest, gefolgt von zwei
              Offizieren von Eichmanns Personal, SS-Obersturmbannführer Hermann
              Krumey und SS-Hauptsturmführer Otto Hunsche. Auch Hans Günther,
              sein Stellvertreter SS-Obersturmführer Gerhard Günnel und Karl
              Rahm sind anwesend. Selbst der Vorsitzende des Ältestenrates
              Benjamin Murmelstein wird eingeladen (16. 4).
            </p>
