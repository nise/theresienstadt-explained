                        Grundlagenwissen
                      </span>
                      <span v-else-if="estimatedAbility < 1.5">
                        vertieftes Wissen
                      </span>
                      <span v-else>spezialisiertes Wissen</span>
                    </p>
                  </div>
                </div>

                <button
                  class="btn btn-secondary w-100"
                  @click="restartTest"
                  style="background-color: #c10000"
                >
                  Test wiederholen
                </button>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  </div>
</template>

<script>
import axios from "axios";
export default {
  data() {
    return {
      testStarted: false,
      testCompleted: false,
      currentQuestionIndex: 0,
      maxQuestions: 10,
      selectedAnswer: null,
      answered: false,
      isCorrect: false,
      correctAnswers: 0,
      estimatedAbility: 0, // Theta parameter in IRT (ranges roughly -3 to +3)
      allQuestions: [],

      askedQuestions: [],
      questionHistory: [],
    };
  },
  mounted() {
    this.getQuestionData();
  },

  computed: {
    currentQuestion() {
      if (this.askedQuestions.length > this.currentQuestionIndex) {
        return this.askedQuestions[this.currentQuestionIndex];
      }
      return null;
    },

    difficultyLabel() {
      if (!this.currentQuestion) return "";
      const diff = this.currentQuestion.difficulty;
      if (diff < -0.5) return "Leicht";
      if (diff < 0.5) return "Mittel";
      if (diff < 1.5) return "Schwer";
      return "Sehr schwer";
    },

    progressPercent() {
      return ((this.currentQuestionIndex + 1) / this.maxQuestions) * 100;
    },

    abilityPercent() {
      // Convert ability (-3 to +3) to percentage (0 to 100)
      return Math.round(((this.estimatedAbility + 3) / 6) * 100);
    },
  },

  methods: {
    async getQuestionData() {
      try {
        const response = await axios.get("./data/history-questions.json");
        this.allQuestions = response.data;
        console.log("q", this.allQuestions);
      } catch (error) {
        console.log("Error:", error);
      }
    },
    startTest() {
      this.testStarted = true;
      this.selectNextQuestion();
    },

    selectNextQuestion() {
      if (this.allQuestions.length == 0) {
        return;
      }
      // CAT algorithm: select question closest to current ability estimate
      const unusedQuestions = this.allQuestions.filter(
        (q) => !this.askedQuestions.includes(q)
      );

      if (unusedQuestions.length === 0) {
        this.completeTest();
        return;
      }

      // Find question with difficulty closest to estimated ability
      const nextQuestion = unusedQuestions.reduce((best, current) => {
        const bestDiff = Math.abs(best.difficulty - this.estimatedAbility);
        const currentDiff = Math.abs(
          current.difficulty - this.estimatedAbility
        );
        return currentDiff < bestDiff ? current : best;
      });

      this.askedQuestions.push(nextQuestion);
    },

    selectAnswer(index) {
      if (!this.answered) {
        this.selectedAnswer = index;
      }
    },

    submitAnswer() {
      this.answered = true;
      this.isCorrect = this.selectedAnswer === this.currentQuestion.correct;

      if (this.isCorrect) {
        this.correctAnswers++;
      }

      // Update ability estimate using simple IRT-like approach
      this.updateAbilityEstimate();

      // Record this question in history
      this.questionHistory.push({
        question: this.currentQuestion,
        correct: this.isCorrect,
        selectedAnswer: this.selectedAnswer,
      });
    },

    updateAbilityEstimate() {
      // Simplified IRT ability estimation
      // In real CAT, this would use Maximum Likelihood Estimation
      const difficulty = this.currentQuestion.difficulty;
      const stepSize = 0.3; // Learning rate

      if (this.isCorrect) {
        // If correct and question was hard, increase ability more
        this.estimatedAbility +=
          stepSize * (1 + (difficulty - this.estimatedAbility) * 0.3);
      } else {
        // If incorrect and question was easy, decrease ability more
        this.estimatedAbility -=
          stepSize * (1 + (this.estimatedAbility - difficulty) * 0.3);
      }

      // Keep ability in reasonable range
      this.estimatedAbility = Math.max(-3, Math.min(3, this.estimatedAbility));
    },

    nextQuestion() {
      this.selectedAnswer = null;
      this.answered = false;
      this.isCorrect = false;
      this.currentQuestionIndex++;

      if (this.currentQuestionIndex >= this.maxQuestions) {
        this.completeTest();
      } else {
        this.selectNextQuestion();
      }
    },

    completeTest() {
      this.testCompleted = true;
      this.testStarted = false;
    },

    restartTest() {
      this.testStarted = false;
      this.testCompleted = false;
      this.currentQuestionIndex = 0;
      this.selectedAnswer = null;
      this.answered = false;
      this.isCorrect = false;
      this.correctAnswers = 0;
      this.estimatedAbility = 0;
      this.askedQuestions = [];
      this.questionHistory = [];
    },
  },
};
</script>

