        <div class="card sticky-top" style="top: 20px">
          <div
            class="card-header text-white"
            style="background-color: #c10000"
          ></div>
          <div class="card-body">
            <!-- Test not started -->
            <div v-if="!testStarted && !testCompleted">
              <p hidden>
                Dieser adaptive Test passt sich Ihrem Niveau an. Sie erhalten
                Fragen basierend auf Ihren vorherigen Antworten.
              </p>
              <button
                class="btn btn-secondary btn-lg w-100"
                @click="startTest"
                style="background-color: #c10000"
              >
                Teste dein Leseverständnis
              </button>
            </div>

            <!-- Test in progress -->
            <div v-if="testStarted && !testCompleted">
              <div class="mb-3">
                <div class="d-flex justify-content-between mb-2">
                  <span
                    ><strong
                      >Frage {{ currentQuestionIndex + 1 }}/{{
                        maxQuestions
                      }}</strong
                    ></span
                  >
                  <span class="badge">{{ difficultyLabel }}</span>
                </div>
                <div class="progress mb-2" style="height: 8px">
                  <div
                    class="progress-bar"
                    :style="{
                      width: progressPercent + '%',
                      backgroundColor: '#c10000',
                    }"
                  ></div>
                </div>
                <small hidden class="text-muted"
                  >Geschätzte Fähigkeit:
                  {{ estimatedAbility.toFixed(2) }}</small
                >
              </div>

              <div class="question-container">
                <p class="lead">{{ currentQuestion.question }}</p>

                <div class="list-group">
                  <button
                    v-for="(option, index) in currentQuestion.options"
                    :key="index"
                    class="list-group-item list-group-item-action"
                    :class="
                      'list-group-item list-group-item-action' +
                      {
                        active: selectedAnswer === index,
                        'list-group-item-success':
                          answered && index === currentQuestion.correct,
                        'list-group-item-danger':
                          answered &&
                          selectedAnswer === index &&
                          index !== currentQuestion.correct,
                      }
                    "
                    :disabled="answered"
                    @click="selectAnswer(index)"
                  >
                    {{ option }}
                  </button>
                </div>

                <div v-if="answered" class="mt-3">
                  <div
                    :class="
                      isCorrect ? 'alert alert-success' : 'alert alert-danger'
                    "
                  >
                    <strong>{{
                      isCorrect ? "Richtig!" : "Leider falsch!"
                    }}</strong>
                    <p class="mb-0 mt-2">{{ currentQuestion.explanation }}</p>
                  </div>
                  <button
                    class="btn btn-secondary w-100"
                    @click="nextQuestion"
                    style="background-color: #c10000"
                  >
                    {{
                      currentQuestionIndex < maxQuestions - 1
                        ? "Nächste Frage"
                        : "Test beenden"
                    }}
                  </button>
                </div>

                <button
                  v-if="!answered && selectedAnswer !== null"
                  class="btn btn-secondary w-100 mt-3"
                  style="background-color: #c10000"
                  @click="submitAnswer"
                >
                  Antwort bestätigen
                </button>
              </div>
            </div>

            <!-- Test completed -->
            <div v-if="testCompleted">
              <div class="text-center">
                <h3 class="mb-3">Test abgeschlossen!</h3>
                <div class="card mb-3">
                  <div class="card-body" style="text-align: left">
                    Sie hatten {{ correctAnswers }} von
                    {{ maxQuestions }} Aufgaben richtig gelöst.
                    <br />
                    Ihr geschätztes Leseverständnis beträgt somit:
                    <div class="progress mt-2" style="height: 20px">
                      <div
                        class="progress-bar bg-secondary"
                        :style="{
                          width: abilityPercent + '%',
                          backgroundColor: '#c10000',
                        }"
                      >
                        {{ abilityPercent }}%
