        <h3 class="timelineMajorMarker mt-4">1988–1998</h3>
        <p>
          Dr. Regina Mihal Friedman von der Universität Tel-Aviv "entdeckt" in
          Yad Vashem den Theresienstädter Film und schließt ihre Studie mit der
          Feststellung ab, dass <i>Theresienstadt</i> in der Generationenkluft
          als "Tribut unzerstörbaren Geistes der jüdischen und der menschlichen
          Kreativität und Kampfkraft" verstanden werden kann.
        </p>
        <p>
          Einen Satz neuer Dokumente und Angaben über den Verlauf der
          Dreharbeiten in den Jahren 1944 und 1945 bringen die Studien des
          niederländischen Historikers Karel Margry. Dieser weist darauf hin,
          dass der überlieferte Name des Films
          <i>Der Führer schenkt den Juden eine Stadt</i> nicht original ist. In
          den Archiven von Yad Vashem befindet sich das Initialfragment des
          Films mit der ursprünglichen Überschrift:
          <i
            >Theresienstadt. <span class="nz">Ein Dokumentarfilm</span> aus dem
            Jüdischen Siedlungsgebiet</i
          >. Es ist ein Fragment, ursprünglich von Jiří Lauscher gefunden.
        </p>
        <p>
          In einem polnischen Archiv identifiziert Karl Margry eine bis dahin
          unbekannte Filmaufnahme über
          <span class="nz">die Dreharbeiten</span> im Jahr 1942, dort unter dem
          <i>Namen Obóz koncentracyjny w Teresinie</i> bewahrt.
        </p>

        <h3 class="timelineMajorMarker mt-4">2004</h3>
        <p>
          Im Nationalfilmarchiv (NFA) in Prag identifiziert Eva Strusková
          Auschnitte, die einst Irena Dodalová aus dem Schneideraum
          hinausgetragen hat und die ihre Reise bei Lubor M. Dohnal, Professor
          an der Prager FAMU beendet haben. Im NFA sind sie unter dem Namen
          <i>Terezín 1942 (Ausschnitte)</i> eingeordnet. Der Rolle der Irena
          Dodalová während der Dreharbeiten im Jahre 1942 hat Eva Strusková
          mehrere wissenschaftliche Studien gewidmet.
        </p>

        <h3 class="timelineMajorMarker mt-4">2015</h3>
        <p>
          Beim Neisse Filmfestival wird erstmals eine didaktisch aufberietete
          und kommentierte Fassung des Film gezeigt.
        </p>
