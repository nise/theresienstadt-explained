              Residenz K.H. Franks, eine Privatvorführung des Films statt, an
              der die ausgewählten SS-Offiziere Hans Günther und Karl Rahm
              teilnehmen. Eine Projektion findet auch in Theresienstadt statt,
              diesmal für das Internationale Komitee des Roten Kreuzes. Unter
              den Teilnehmern sind dr. Otto Lehner und Paul Dunant, der
              Schweizer Diplomat Buchmüller, der Kommandeur
              <span class="nz">der Sicherheitspolizei</span> und des
              Sicherheitsdienstes im Protektorat SS-Oberführer Erwin Weinmann,
              zwei Beamte <span class="nz">des Auswärtigen</span> Amtes -
              Legationsrat Eberhard von Thadden und Botschafter Erich von
              Luckwald, und schließlich
              <span class="nz">SS-Obersturmbannführer</span> Adolf Eichmann (6.
              4).
            </p>
            <p>
