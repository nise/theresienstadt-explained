      Dekontextualisierung
      Bei der Dekontextualisierung wird ein Nachrichteninhalt oder ein Ereignis aus seinem tatsächlichen Kontext herausgelöst, so dass das Ereignis nur für sich, also isoliert, wahrgenommen wird. Bei Ereignissen (zum Beispiel einer gewaltsamen Demonstration) fehlt die Vorgeschichte oder der politische Hintergrund. Das Ereignis oder die Nachricht kann daher nicht von Rezipienten eingeordnet und interpretiert werden. Zum richtigen Verständnis muss der ursprüngliche Kontext wiederhergestellt werden.

      Kognitive Dissonanz
      Menschen bevorzugen konsistente Vorstellungen, harmonische Konzepte, in denen alle Teile zueinander passen. Diese Tendenz kann manipulativ ausgenutzt werden. Nehmen wir an, ein Meinungsforscher stellt fest, dass eine bestimmte Gruppe von Menschen seinen Kandidaten für den Senator hasst, aber den Schauspieler A liebt. Sie verwenden die Billigung des Kandidaten A von ihrem Kandidaten, um die Meinung der Menschen zu ändern, weil die Menschen Inkonsistenz nicht tolerieren können. Sie sind gezwungen, den Schauspieler entweder nicht zu mögen oder den Kandidaten zu mögen. 

      Normaler Mensch
Mit dem Hinweis auf die „einfachen Leute“ oder „normalen Menschen“ wird versucht, das Publikum davon zu überzeugen, dass die Positionen des Propagandisten den gesunden Menschenverstand widerspiegeln. Es soll das Vertrauen des Publikums gewinnen, indem es auf die übliche Art und Weise des Zielpublikums kommuniziert. Propagandisten verwenden gewöhnliche Sprache und Verhaltensweisen (und kleiden ihre Botschaft in persönliche und audiovisuelle Kommunikation), um zu versuchen, ihren Standpunkt mit dem des Durchschnittsbürgers zu identifizieren. 

Berufung auf berühmte Menschen
Diese Art von Propaganda beruft sich auf berühmte Menschen oder auf attraktive und glücklich erscheinende Menschen. 

Übertreibung
Eine Übertreibung liegt vor, wenn Eigenschaften verstärkt, vergröbert und hervorgehoben werden, so dass die Wirklichkeit verzerrt erscheint.

Euphorie
Die Verwendung eines Ereignisses, das Euphorie oder Glück erzeugt, oder die Verwendung eines ansprechenden Ereignisses, um die Moral zu steigern. Euphorie kann erzeugt werden, indem ein Feiertag deklariert wird, Luxusartikel zur Verfügung gestellt werden oder eine Militärparade mit Marschbändern und patriotischen Botschaften aufgebaut wird.

Wiederholung
Dies ist die Wiederholung eines bestimmten Symbols oder Slogans, damit sich das Publikum daran erinnert. Dies kann in Form eines Jingle oder eines Bildes sein, das auf fast alles im Bild / in der Szene platziert wird. Dazu gehört auch die Verwendung von unterschwelligen Phrasen, Bildern oder anderen Inhalten in einer Propaganda.

Berufung auf Autoritäten
Die Berufung auf Autoritäten oder Experten zitieren oder berufen sich auf prominente Persönlichkeiten des öffentlichen Lebens, besonders auch Wissenschaftler, um Positionen, Ideen, Argumente oder Vorgehensweisen überzeugend, allgemeinverbindlich, vorbildlich oder wertvoll wirken zu lassen.

Halbwahrheit
Eine halbe Wahrheit ist eine betrügerische Aussage, die ein gewisses Element der Wahrheit enthält. Es gibt verschiedene Formen: Die Aussage kann teilweise wahr sein, die Aussage kann völlig zutreffend sein, aber nur ein Teil der gesamten Wahrheit, oder sie kann ein betrügerisches Element verwenden, z die Wahrheit zu täuschen, ausweichen, beschuldigen oder falsch darstellen. 

Rosinenpicken
Unter diesem Begriff verbirgt sich eine Technik zur Steuerung der Wahrnehmung, in dem die Aufmerksamkeit des Publikums nur auf die herausgepickten Themen (Rosinen) gelenkt wird, während andere Themen gar nicht angesprochen werden. Unter Rosinenpicken versteht man somit die Auswahl der gewünschten Wahrheit und das Vermischen mit einigen Wahrheiten, die das Publikum hören möchte. 
